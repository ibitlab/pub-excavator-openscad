#!/usr/bin/env bash
# Одноразове перегрупування stl/ по теках-завданнях друку.
#
# Файли ПЕРЕМІЩУЮТЬСЯ (mv), не копіюються: після запуску в корені stl/ лишається
# тільки цей скрипт і підпапки. Зворотного режиму немає — щоб отримати плаский
# набір назад, перегенеруй його через print3d-parts/make.sh.
#
# Тека = одне завдання слайсера. Межі проведені по трьох ознаках, які не можна
# змішати в одному завданні:
#   1. КОЛІР — що деталь зображає в машині (конструкційна сталь, зносостійка,
#      покупний гідроциліндр, кругла заготовка);
#   2. ВИСОТА ШАРУ — 0.20 мм для всього, 0.12 для дрібних круглих деталей
#      (втулки, бобишки, пальці): на Ø6–13 мм шар 0.2 дає гранований циліндр;
#   3. ПІДПОРИ — вмикати їх треба рівно в одному завданні (гідроциліндри).
#      Це і є головна причина ділення: ввімкнеш підпори на весь стіл — отримаєш
#      їх там, де вони не потрібні, а «підпори всюди» ще й заллють нутро труб.
#
# Числа в коментарях нижче — з print3d-parts/BOM.md, тобто з ВИМІРЯНИХ STL.
#
# Увага: make.sh рендерить знову в корінь stl/, тож після перезбирання набору
# запусти цей скрипт ще раз — інакше в корені й у теках будуть дублікати.
set -eu
cd "$(dirname "$0")"

moved=0
skipped=""

grp() {
    dir=$1
    shift
    mkdir -p "$dir"
    for n in "$@"; do
        found=0
        for f in "${n}"_*.stl; do
            [ -e "$f" ] || continue
            mv -f "$f" "$dir/"
            moved=$((moved + 1))
            found=1
        done
        [ "$found" = 1 ] || skipped="$skipped $n"
    done
}

# --- 1. Конструкційна сталь: труби, пластини, накладки, вилки, сідла, ківш ----
# Корпусний колір машини. 0 % полиць у всіх, крім труб — а в труб це не звис,
# а стеля порожнистої труби: місток 18 мм (рукоять) і 22 мм (стріла), FDM кладе
# його без підпор. ПІДПОРИ ВИМКНУТИ: «всюди» заллє нутро труб намертво.
# Brim окремо: обичайка ковша 18 (контакт 112 мм² при висоті 57.6 мм) і труби.
grp "1_корпус_жовтий_шар0.20_без-підпор" \
    01 02 03 `# труби стріли (2 сегменти) і рукояті` \
    04 05 06 07 08 09 10 `# стріла: щоки, накладки, вилки B і D, вежа F` \
    11 12 13 14 15 `# рукоять: щоки, ребро, вилка H, накладки кінця` \
    16 17 `# коромисло й тяги` \
    18 19 20 21 22 `# ківш: обичайка, боковини, накладка, ребро губи, вуха` \
    26 `# плити поворотної колони`

# --- 2. Зносостійка сталь -----------------------------------------------------
# У металі це ІНША сталь (список BOM_WEAR), тому й філамент інший — темний.
# Підпори не потрібні (0 % полиць), але контакт малий: зуб 105 мм², смуга 49 мм².
# Brim обов'язковий.
grp "2_зносостійке_темне_шар0.20_brim" \
    23 24 25 `# ніж, зуби ×3, смуги зносу на п'яті`

# --- 3. Гідроциліндри ---------------------------------------------------------
# Єдине завдання з УВІМКНЕНИМИ підпорами: у гільз 7–9 % полиць на висоті
# 0–11.5 мм (плоске вушко над круглим корпусом). Тільки «від столу».
# Гільзи й штоки друкуються РАЗОМ і однаковими налаштуваннями: вони ходять одне
# в одному із зазором 0.35 мм, і різні завдання цей зазор зіпсують.
# Хочеш хром на штоках — став паузу на зміну філаменту, а не окреме завдання.
grp "3_циліндри_сіре_шар0.20_підпори-від-столу" \
    27 28 `# стріла: гільза Ø63 + шток Ø40` \
    29 30 `# рукоять: гільза Ø50 + шток Ø25` \
    31 32 `# ківш: гільза Ø50 + шток Ø25`

# --- 4. Втулки, бобишки, шайби ------------------------------------------------
# Кругла заготовка — сріблястий. Шар 0.12: стінки 1–2 мм, Ø7.8–15.2 мм.
# Стоять на кільці, контакт 27–152 мм² — brim на все завдання.
# Підпори НЕ вмикати: отвір вертикальний, стінки прямовисні, звисів немає.
grp "4_втулки-бобишки_сріблясте_шар0.12_brim" \
    33 34 35 36 `# втулки осей A, B, E, R` \
    37 38 39 40 `# бобишки G, J, тяги ×4, зовнішні вуха ковша` \
    41 42 `# розпірка Q, упорні шайби B (0.4 мм — дві лінії)`

# --- 5. Пальці ----------------------------------------------------------------
# Сріблясті, шар 0.12: це єдині деталі з посадкою — Ø5.6 і Ø4.6 мм, увесь зазор
# знятий з пальця (FIT_PIN 0.40). Стоять на голівці, контакт 30–41 мм² → brim.
# Окремо ще й тому, що їх найімовірніше доведеться передрукувати, якщо шарнір
# вийде тугим або бовтким.
grp "5_пальці_сріблясте_шар0.12_brim" \
    43 44 45 46 47 `# Ø30: осі A, C, B, D, E` \
    48 49 50 51 52 `# Ø25: осі F, G, H, J, Q` \
    53 `# Ø30: вісь R коромисла`

echo "переміщено файлів: $moved"
[ -z "$skipped" ] || echo "НЕ ЗНАЙДЕНО (уже згруповані або не згенеровані):$skipped"

left=$(ls *.stl 2>/dev/null | wc -l | tr -d ' ')
[ "$left" = 0 ] || {
    echo "УВАГА: у корені лишилося $left STL поза групами:"
    ls *.stl | sed 's/^/  /'
    exit 1
}
