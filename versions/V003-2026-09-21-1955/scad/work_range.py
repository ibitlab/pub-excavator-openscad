def bucket_outline():
    """Силует ковша у власній системі (E = 0, x — до зуба) з tools/bucket.py."""
    pr = bkt.profile(bkt.BUCKET, kin.GEOM)
    u = unary_union([pr['side'], pr['blade'], pr['tooth']])
    return list(zip(*u.exterior.xy))


BK = bucket_outline()


def place(poly, origin, a):
    """Силует у світових координатах: поворот на a° і перенос у origin."""
    return [kin.add(origin, kin.rot(p, a)) for p in poly]

