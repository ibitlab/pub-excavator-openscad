    y = 0.820
    for k in 'ABCDEFGHJ':
        fig.text(tx, y, k, fontsize=10.5, weight='bold', color='w',
                 bbox=dict(boxstyle='circle,pad=0.3', fc='#1f4e9c', ec='none'))
        fig.text(tx + 0.026, y, t['dims'][k], fontsize=10, va='baseline')
        fig.text(0.985, y, f'{m[k][0]:.0f}', fontsize=11, weight='bold', ha='right', va='baseline')
        y -= 0.041
    # Перенесення вручну: шрифт пропорційний, довгі рядки мовчки вилазять за аркуш.
