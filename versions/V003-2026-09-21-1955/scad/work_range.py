# ---------------------------------------------------------------- кінематика
def sweep(g, n_t=97, n_p=97, n_o=45):
    """Хмара положень вістря зуба на всьому ході трьох циліндрів."""
    th0, th1 = kin.boom_range(g)
    ps0, ps1 = kin.stick_range(g)
    _, om0, om1, _ = kin.bucket_range(g)
    out = []
    for t in kin.frange(th0, th1, n_t):
        bp = kin.boom_points(g, t)
        for p in kin.frange(ps0, ps1, n_p):
            sp = kin.stick_points(g, bp, p)
            for o in kin.frange(om0, om1, n_o):
                a = sp['a_s'] - o                      # напрямок осі ковша E→зуб
                tip = kin.add(sp['E'], kin.rot((g['tip'], 0), a))
                out.append(dict(x=tip[0], y=tip[1], axis=a, th=t, psi=p, om=o, E=sp['E']))
    return dict(pts=out, th=(th0, th1), ps=(ps0, ps1), om=(om0, om1))


def outline(pts, bins=540):
    """Зовнішня і внутрішня межі зони в полярних координатах з центром у осі A."""
    lo = [None] * bins
    hi = [None] * bins
    for p in pts:
        r = math.hypot(p['x'], p['y'])
        i = int((math.degrees(math.atan2(p['y'], p['x'])) + 180.0) / 360.0 * bins) % bins
        if hi[i] is None or r > hi[i]:
            hi[i] = r
        if lo[i] is None or r < lo[i]:
            lo[i] = r
    outer, inner = [], []
    for i in range(bins):
        if hi[i] is None:
            continue
        a = math.radians((i + 0.5) / bins * 360.0 - 180.0)
        outer.append((hi[i] * math.cos(a), hi[i] * math.sin(a)))
        inner.append((lo[i] * math.cos(a), lo[i] * math.sin(a)))
    return outer, inner


def cross_y(poly, y):
    """Найбільший x, де ламана перетинає горизонталь y (лінійна інтерполяція)."""
    best = None
    for (x0, y0), (x1, y1) in zip(poly, poly[1:]):
        if (y0 - y) * (y1 - y) <= 0 and abs(y1 - y0) > 1e-9:
            x = x0 + (x1 - x0) * (y - y0) / (y1 - y0)
            if best is None or x > best:
                best = x
    return best


def measures(g, sw, outer, inner):
    """Характерні розміри — усі з хмари положень, жодного вписаного руками."""
    pts = sw['pts']
    ground = -g['A_height']
    xs_ground = cross_y(outer, ground)
    xs_ground_in = cross_y(inner, ground)

    deepest = min(pts, key=lambda p: p['y'])
    highest = max(pts, key=lambda p: p['y'])
    farthest = max(pts, key=lambda p: p['x'])
    # Вивантаження: ківш розкрито повністю (omega на нижній межі ходу), і міряється
    # не зуб, а НАЙНИЖЧА точка ковша — під нею має пройти борт кузова.
    om0 = sw['om'][0]
    dump, dump_y = None, -1e9
    for p in pts:
        if abs(p['om'] - om0) > 1e-6:
            continue
        low = min(q[1] for q in place(BK, p['E'], p['axis']))
        if low > dump_y:
            dump, dump_y = p, low
    e_high = max(p['E'][1] for p in pts)

    # вертикальна стінка: вісь ковша ближча до вертикалі, ніж 20°, і зуб іде суцільним
    # стовпом від землі вниз. Крок стовпа 25 мм — дрібніше сітка положень не дає.
    step = 25.0
    wall = 0.0
    cols = {}
    for p in pts:
        d = abs(((p['axis'] + 90.0) % 180.0) - 90.0)    # відхилення осі ковша від вертикалі
        if d > 20.0 or p['y'] > ground:
            continue
        cols.setdefault(round(p['x'] / step), set()).add(round((ground - p['y']) / step))
    for levels in cols.values():
        if 0 not in levels:          # стовп має починатися від самої землі
            continue
        d = 0
        while (d + 1) in levels:     # і йти вниз без розривів
            d += 1
        wall = max(wall, d * step)

    return dict(
        A=(farthest['x'], farthest),
        B=(xs_ground, None),
        C=(ground - deepest['y'], deepest),
        D=(wall, None),
        E=(highest['y'] - ground, highest),
        F=(dump_y - ground, dump),
        G=(g['A_height'], None),
        H=(xs_ground_in, None),
        J=(e_high - ground, None),
    )


def pose(g, p):
    """Ламана стріла→рукоять і силует ковша для положення з хмари."""
    bp = kin.boom_points(g, p['th'])
    sp = kin.stick_points(g, bp, p['psi'])
    return [bp['A'], bp['K'], bp['B'], sp['E']], place(BK, sp['E'], p['axis'])


